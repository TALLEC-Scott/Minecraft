def data_uri(path):
    return "data:image/png;base64," + base64.b64encode((ROOT / path).read_bytes()).decode()


STANDALONE_HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<style>*,*::before,*::after{box-sizing:border-box}body{margin:0}img{max-width:100%}[hidden]{display:none!important}
:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}</style>
"""


def write_html(data, layers, out, standalone=False):
    icon_of = {}  # name -> data URI
    for b in data["blocks"]:
        icon_of[b["name"]] = data_uri(layers[b["iconLayer"]])
    for i in data["items"]:
        icon_of[i["name"]] = data_uri(i["icon"])

    def icon(name, cls="ico"):
        src = icon_of.get(name)
        return f'<img class="{cls}" src="{src}" alt="">' if src else '<span class="ico ico-empty"></span>'

    def slot(name, count=1):
        if not name:
            return '<span class="slot"></span>'
        n = f'<b class="n">{count}</b>' if count > 1 else ""
        return f'<span class="slot" title="{html.escape(name)}">{icon(name)}{n}</span>'

    e = html.escape
    tier = {1: "Wood", 2: "Stone", 3: "Iron"}
    blocks_rows = []
    for b in data["blocks"]:
        hard = "—" if b["hardness"] < 0 else f'{b["hardness"]:g}'
        tool = TOOL_LABEL[b["bestTool"]]
        need = '<span class="chip warn">needs tool</span>' if b["needsTool"] else ""
        traits = "".join(f'<span class="chip">{e(t)}</span>' for t in block_traits(b))
        drop = []
        if b["drop"]:
            d = b["drop"]
            drop.append(f'{icon(d["name"], "ico sm")}{e(d["name"])}')
        if b["chanceDrop"]:
            d = b["chanceDrop"]
            drop.append(f'{icon(d["name"], "ico sm")}{e(d["name"])} <span class="muted">1 in 200</span>')
        drop_html = "<br>".join(drop) if drop else '<span class="muted">nothing</span>'
        blocks_rows.append(
            f'<tr data-q="{e(b["name"].lower())}"><td>{slot(b["name"])}</td>'
            f'<td><strong>{e(b["name"])}</strong><div class="tags">{traits}</div></td>'
            f'<td class="num">{b["id"]}</td><td class="num">{hard}</td><td>{tool} {need}</td>'
            f'<td class="num">{seconds(b["ticksHand"])}</td><td class="num">{seconds(b["ticksWood"])}</td>'
            f'<td class="num">{seconds(b["ticksStone"])}</td><td>{drop_html}</td></tr>'
        )

    tool_rows, food_rows, mat_rows = [], [], []
    for i in data["items"]:
        q = e(i["name"].lower())
        if i["tool"] != "none":
            dps = i["damage"] * i["attackSpeed"]
            tool_rows.append(
                f'<tr data-q="{q}"><td>{slot(i["name"])}</td><td><strong>{e(i["name"])}</strong></td>'
                f'<td class="num">{i["id"]}</td><td>{i["tool"]}</td><td>{tier.get(i["tier"], "—")}</td>'
                f'<td class="num">{i["damage"]:g}</td><td class="num">{i["attackSpeed"]:g}</td>'
                f'<td class="num">{dps:.1f}</td></tr>'
            )
        elif i["hunger"] > 0:
            pips = '<span class="pip"></span>' * (i["hunger"] // 2) + (
                '<span class="pip half"></span>' if i["hunger"] % 2 else "")
            food_rows.append(
                f'<tr data-q="{q}"><td>{slot(i["name"])}</td><td><strong>{e(i["name"])}</strong></td>'
                f'<td class="num">{i["id"]}</td><td><span class="pips">{pips}</span> '
                f'<span class="num">{i["hunger"]}</span></td><td class="num">{i["saturation"]:g}</td>'
                f'<td class="num">{i["stack"]}</td></tr>'
            )
        else:
            mat_rows.append(
                f'<tr data-q="{q}"><td>{slot(i["name"])}</td><td><strong>{e(i["name"])}</strong></td>'
                f'<td class="num">{i["id"]}</td><td class="num">{i["stack"]}</td></tr>'
            )

    recipe_cards = []
    for r in data["recipes"]:
        n = 3 if r["needsTable"] else 2
        cells = []
        for y in range(n):
            for x in range(n):
                name = r["cells"][y * r["width"] + x] if x < r["width"] and y < r["height"] else None
                cells.append(slot(name))
        res = r["result"]
        where = "Crafting table" if r["needsTable"] else "Inventory"
        recipe_cards.append(
            f'<figure class="recipe" data-q="{e(res["name"].lower())}">'
            f'<div class="grid g{n}">{"".join(cells)}</div><span class="arrow" aria-hidden="true">→</span>'
            f'{slot(res["name"], res["count"])}<figcaption><strong>{e(res["name"])}</strong>'
            f'<span class="muted">{where}</span></figcaption></figure>'
        )

    mob_rows = []
    for m in data["mobDrops"]:
        if m["item"]:
            count = f'{m["min"]}' if m["min"] == m["max"] else f'{m["min"]}–{m["max"]}'
            drop = f'{icon(m["item"], "ico sm")}{e(m["item"])} <span class="muted">×{count}</span>'
        else:
            drop = '<span class="muted">nothing</span>'
        mob_rows.append(f'<tr data-q="{e(m["mob"].lower())}"><td><strong>{e(m["mob"])}</strong></td><td>{drop}</td></tr>')

    counts = (len(data["blocks"]), len(data["items"]), len(data["recipes"]))
    page = TEMPLATE
    for key, val in {
        "BLOCK_ROWS": "\n".join(blocks_rows),
        "TOOL_ROWS": "\n".join(tool_rows),
        "FOOD_ROWS": "\n".join(food_rows),
        "MAT_ROWS": "\n".join(mat_rows),
        "RECIPES": "\n".join(recipe_cards),
        "MOB_ROWS": "\n".join(mob_rows),
        "N_BLOCKS": str(counts[0]),
        "N_ITEMS": str(counts[1]),
        "N_RECIPES": str(counts[2]),
        "FIST_DMG": f'{data["fist"]["damage"]:g}',
        "FIST_SPD": f'{data["fist"]["attackSpeed"]:g}',
    }.items():
        page = page.replace("{{" + key + "}}", val)
    if standalone:
        # The page's own <title>/<style> stay in the head; the rest is body.
        split = page.index('<div class="wrap">')
        page = STANDALONE_HEAD + page[:split] + "</head>\n<body>\n" + page[split:] + "\n</body>\n</html>\n"
    out.write_text(page)


