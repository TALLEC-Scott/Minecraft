"""Item wiki generator (standard library only; run with `uv run`).

Reads the JSON that scripts/item_wiki (item_wiki.cpp) dumps from the game's
own tables and writes docs/wiki/Items.md, plus a self-contained HTML page
(sprites embedded) when --html is given.

usage: uv run scripts/item_wiki.py <items.json> [--html out.html [--standalone]]
--standalone writes a complete HTML document (for serving on the site,
e.g. /wiki.html); without it the page body suits an embedding viewer.
Run from the project root (it reads src/texture_array.cpp for block icons).
"""
import base64
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TICKS_PER_SECOND = 20


def texture_paths():
    """Block icon PNG per texture-array layer, in layer order."""
    src = (ROOT / "src/texture_array.cpp").read_text()
    body = src[src.index("TEXTURE_PATHS[] = {"):]
    body = body[: body.index("};")]
    return re.findall(r'"(assets/[^"]+\.png)"', body)


def seconds(ticks):
    if ticks < 0:
        return "unbreakable"
    if ticks == 0:
        return "instant"
    return f"{ticks / TICKS_PER_SECOND:g} s"


def drop_text(block):
    parts = []
    if block["drop"]:
        d = block["drop"]
        parts.append(f'{d["name"]}' + (f' ×{d["count"]}' if d["count"] > 1 else ""))
    if block["chanceDrop"]:
        parts.append(f'{block["chanceDrop"]["name"]} (1 in 200)')
    if not parts:
        return "nothing"
    return ", ".join(parts)


def block_traits(b):
    traits = []
    if b["liquid"]:
        traits.append("liquid")
    elif b["plant"]:
        traits.append("plant")
    elif b["solid"]:
        traits.append("solid" if b["opaque"] else "see-through")
    if b["light"]:
        traits.append(f'light {b["light"]}')
    return traits


TOOL_LABEL = {"none": "any", "pickaxe": "pickaxe", "axe": "axe", "shovel": "shovel", "sword": "sword"}


# ---------------------------------------------------------------- Markdown

def write_markdown(data, layers, out):
    lines = [
        "# Items",
        "",
        "Every block and item in the game and how it behaves in Survival. Generated by",
        "`scripts/item_wiki.py` from the game's own tables (`item.h`, `mining.h`, `recipes.h`,",
        "`mob_drops.h`); regenerate it after changing them:",
        "",
        "```bash",
        "g++ -std=c++20 -I include -I Libraries/include scripts/item_wiki.cpp -o scripts/item_wiki",
        "./scripts/item_wiki > /tmp/items.json && uv run scripts/item_wiki.py /tmp/items.json",
        "```",
        "",
        "Break times follow Minecraft's rules: a block's hardness, sped up by the right tool",
        "(wood ×2, stone ×4). Blocks marked *needs tool* drop nothing without it and take",
        "more than three times longer.",
        "",
        "## Blocks",
        "",
        "| | Block | ID | Hardness | Best tool | By hand | Wooden tool | Stone tool | Drops | Notes |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for b in data["blocks"]:
        icon = layers[b["iconLayer"]]
        tool = TOOL_LABEL[b["bestTool"]] + (" (needs tool)" if b["needsTool"] else "")
        hard = "–" if b["hardness"] < 0 else f'{b["hardness"]:g}'
        lines.append(
            f'| <img src="../../{icon}" width="16"> | {b["name"]} | {b["id"]} | {hard} | {tool} | '
            f'{seconds(b["ticksHand"])} | {seconds(b["ticksWood"])} | {seconds(b["ticksStone"])} | '
            f'{drop_text(b)} | {", ".join(block_traits(b))} |'
        )
    items = data["items"]
    tools = [i for i in items if i["tool"] != "none"]
    food = [i for i in items if i["hunger"] > 0]
    other = [i for i in items if i["tool"] == "none" and i["hunger"] == 0]
    tier = {1: "wood", 2: "stone", 3: "iron"}
    lines += [
        "",
        "## Tools and weapons",
        "",
        f'Bare hand: {data["fist"]["damage"]:g} damage, {data["fist"]["attackSpeed"]:g} attacks/s. '
        "Damage is in half-hearts; a full-strength hit needs the attack to recharge (1 / attack speed).",
        "",
        "| | Item | ID | Kind | Tier | Damage | Attacks/s | Stack |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for i in tools:
        lines.append(
            f'| <img src="../../{i["icon"]}" width="16"> | {i["name"]} | {i["id"]} | {i["tool"]} | '
            f'{tier.get(i["tier"], "–")} | {i["damage"]:g} | {i["attackSpeed"]:g} | {i["stack"]} |'
        )
    lines += [
        "",
        "## Food",
        "",
        "Hold right click for 1.6 s to eat (only when not full). Food points are half drumsticks.",
        "",
        "| | Item | ID | Food | Saturation | Stack |",
        "|---|---|---|---|---|---|",
    ]
    for i in food:
        lines.append(
            f'| <img src="../../{i["icon"]}" width="16"> | {i["name"]} | {i["id"]} | {i["hunger"]} | '
            f'{i["saturation"]:g} | {i["stack"]} |'
        )
    lines += ["", "## Materials", "", "| | Item | ID | Stack |", "|---|---|---|---|"]
    for i in other:
        lines.append(f'| <img src="../../{i["icon"]}" width="16"> | {i["name"]} | {i["id"]} | {i["stack"]} |')
    lines += [
        "",
        "## Crafting",
        "",
        "Shapes match anywhere in the grid and mirrored. 2×2 recipes work in the inventory (E);",
        "larger ones need a crafting table.",
        "",
        "| Result | Pattern | Where |",
        "|---|---|---|",
    ]
    for r in data["recipes"]:
        rows = []
        for y in range(r["height"]):
            row = r["cells"][y * r["width"]:(y + 1) * r["width"]]
            rows.append(" · ".join(c if c else "—" for c in row))
        res = r["result"]
        name = res["name"] + (f' ×{res["count"]}' if res["count"] > 1 else "")
        lines.append(f'| {name} | {"<br>".join(rows)} | {"crafting table" if r["needsTable"] else "inventory"} |')
    lines += ["", "## Mob drops", "", "| Mob | Drops |", "|---|---|"]
    for m in data["mobDrops"]:
        if m["item"]:
            count = f'{m["min"]}' if m["min"] == m["max"] else f'{m["min"]}–{m["max"]}'
            lines.append(f'| {m["mob"]} | {m["item"]} ×{count} |')
        else:
            lines.append(f'| {m["mob"]} | nothing |')
    lines += [
        "",
        "Item and new block textures: Pixel Perfection (CC BY-SA 4.0), credited in",
        "`assets/Textures/README.md` and `assets/Textures/items/README.md`.",
        "",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))


